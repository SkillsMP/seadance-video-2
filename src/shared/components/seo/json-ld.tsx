/**
 * Generic JSON-LD injection component for structured data.
 * Accepts null to allow builder functions to return null when data is insufficient.
 */
export function JsonLd({ data }: { data: Record<string, unknown> | null }) {
  if (!data) return null;
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(data) }}
    />
  );
}

